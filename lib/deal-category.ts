export function classifyDealCategory(
  category: string | null,
  title: string,
  mall: string | null = null,
): DealCategory {
  const mapped = category ? CATEGORY_MAP[category] : undefined;
  if (mapped) return mapped;
  if (mall && GAME_MALLS.test(mall)) return "게임";
  for (const [type, re] of TITLE_RULES) if (re.test(title)) return type;
  return (category && AMBIGUOUS_FALLBACK[category]) || "기타";
}
